function initialLanguage() {
	// Выбор пользователя — всегда, даже без словаря (тексты клиента тогда на исходном языке):
	// иначе initSession перезагружал бы страницу по кругу. Без выбора — язык по умолчанию, не язык браузера
	return localStorage.getItem(STORAGE_KEY) || DEFAULT;
}

let current = initialLanguage();
document.documentElement.lang = current;

/** Язык интерфейса: код из pgerp.languages (ru, en). */
export function language() {
	return current;
}

/** Сменить язык интерфейса; страницу после этого перезагружают — тексты модулей вычислены при загрузке. */
export function setLanguage(code) {
	current = code;
	localStorage.setItem(STORAGE_KEY, code);
	document.documentElement.lang = code;
}

/** Текст на языке интерфейса; нет перевода (или язык без словаря) — исходный текст. */
export function t(text, ...args) {
	const translated = MESSAGES[current]?.[text] ?? text;
	return args.length === 0 ? translated : translated.replace(/\{(\d+)\}/g, (_, i) => String(args[i] ?? ''));
}

/**
 * Статический текст страниц: data-i18n — текст элемента, data-i18n-attrs="title aria-label" — атрибуты.
 * Исходный текст сохраняется в data-атрибуте, поэтому перевод можно повторить на другой язык.
 */
export function translatePage(root = document) {
	for (const element of root.querySelectorAll('[data-i18n]')) {
		element.dataset.i18nSource ??= element.textContent.trim();
		element.textContent = t(element.dataset.i18nSource);
	}
	for (const element of root.querySelectorAll('[data-i18n-attrs]')) {
		for (const attr of element.dataset.i18nAttrs.split(/\s+/).filter(Boolean)) {
			const key = `i18nSource${attr.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase())}`;
			element.dataset[key] ??= element.getAttribute(attr) ?? '';
			element.setAttribute(attr, t(element.dataset[key]));
		}
	}
}
